create index if not exists appointments_start_idx on appointments(start_at);
create index if not exists appointments_live_idx on appointments(start_at)
  where status in ('pending_payment','confirmed','completed');
drop trigger if exists appointments_updated on appointments;
create trigger appointments_updated before update on appointments
  for each row execute function set_updated_at();

