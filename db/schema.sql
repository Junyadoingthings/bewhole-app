-- THE important constraint. Two live appointments for the same practitioner
-- can never overlap in time — enforced by the database, so a race between two
-- simultaneous bookings ends with one of them getting a 23P01 error rather
-- than both succeeding. Application code must not be trusted with this.
alter table appointments drop constraint if exists appointments_no_overlap;
alter table appointments add constraint appointments_no_overlap
  exclude using gist (
    practitioner_id with =,
    tstzrange(start_at, end_at) with &&
  ) where (status in ('pending_payment','confirmed','completed'));

