-- ============================================================================
-- Be Whole Care — production schema (PostgreSQL / Supabase)
--
-- AUTH MODEL — read this before changing anything.
--
-- This application does NOT use Supabase Auth. It has its own session layer
-- (scrypt password hashing, opaque server-side sessions, signed http-only
-- cookies) in lib/auth/. The Next.js server is therefore the ONLY client of
-- this database: the browser never holds a Supabase key and never issues a
-- query. Authorization is enforced in application code, where every
-- client-scoped read is filtered by the id derived from the session cookie.
--
-- Because of that, RLS here is not the authorization mechanism — it is a
-- blast shield. Every table has RLS enabled with NO permissive policies, so
-- the `anon` and `authenticated` roles can read nothing at all. If a Supabase
-- anon key were ever exposed, it would return zero rows from every table.
-- The server connects as the owner/service role, which bypasses RLS by design.
--
-- Integrity that must not depend on application code lives here instead:
--   * appointments_no_overlap  — double booking is impossible, full stop
--   * foreign keys + checks    — no orphaned or nonsensical rows
--   * unique indexes           — one calendar event per appointment, etc.
-- ============================================================================

