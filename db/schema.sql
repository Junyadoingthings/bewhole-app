-- ==================================================== row level security ====
-- Deny by default, everywhere. No policies are created, so `anon` and
-- `authenticated` can read and write nothing. The application connects as the
-- owner/service role and bypasses RLS; that connection is the only one that
-- ever exists, and it lives on the server.
do $$
declare t text;
begin
  foreach t in array array[
    'users','sessions','profiles','service_categories','services','locations',
    'practitioners','availability_rules','availability_blocks','appointments',
    'payments','payment_events','follow_ups','calendar_events','notifications',
    'notification_logs','resources','workshops','client_notes','consents',
    'audit_logs','settings'
  ] loop
    execute format('alter table %I enable row level security', t);
    execute format('alter table %I force row level security', t);
  end loop;
end $$;

